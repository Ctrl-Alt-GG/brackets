const i18n = getI18n();
i18n.addResourceBundle('en', 'organizer', organizerEnglish);
i18n.addResourceBundle('hu', 'organizer', organizerHungarian);

// The checks that come with Zod, such as a number's range, explain themselves in the page's
// language as well. Only these pages have forms.
const ZOD_LOCALES = { en: zodEnglish, hu: zodHungarian };
function applyZodLocale(language: string | undefined) {
  config(ZOD_LOCALES[language as keyof typeof ZOD_LOCALES]?.() ?? zodEnglish());
}
applyZodLocale(i18n.resolvedLanguage);
i18n.on('languageChanged', () => applyZodLocale(i18n.resolvedLanguage));

/** The organizer pages' texts, in the page's language. */
export function useOrganizerTranslation() {
  return useTranslation('organizer');
}

